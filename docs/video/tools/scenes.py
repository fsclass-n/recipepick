TOTAL = 600


def timeline():
    t = 0.0
    out = []
    for s in SCENES:
        out.append({**s, "start": t})
        t += s["dur"]
    assert abs(t - TOTAL) < 1e-6, f"전체 길이 {t}s ≠ {TOTAL}s"
    return out


def resolve(spec, lines: list) -> float:
    """장면 상대 시간. 숫자 그대로 또는 'L2+5.5'(2번째 문장 시작+5.5초) / 'L3e-1'(3번째 문장 끝-1초)."""
    if isinstance(spec, (int, float)):
        return float(spec)
    import re
    m = re.fullmatch(r"L(\d+)(e?)([+-][\d.]+)?", spec)
    ln = lines[int(m.group(1)) - 1]
    return (ln["end"] if m.group(2) else ln["start"]) + float(m.group(3) or 0)


def subtitle_text(text: str) -> str:
    for k, v in SUB_MAP.items():
        text = text.replace(k, v)
    return text


